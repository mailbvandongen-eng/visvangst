// Bedieningstest: zoeken, uur tikken, getijstation kiezen, uitleg, start zonder GPS
const { chromium } = require('/root/tools/pw/node_modules/playwright-core')
;(async () => {
  const b = await chromium.launch({ executablePath: '/usr/bin/chromium', args: ['--no-sandbox'] })
  const errs = []
  const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, timezoneId: 'Europe/Amsterdam', locale: 'nl-NL' }) // geen GPS-toestemming
  const p = await ctx.newPage()
  p.on('pageerror', e => errs.push(e.message))
  await p.goto('http://localhost:8795/visvangst/')
  await p.waitForTimeout(2500)
  await p.screenshot({ path: '/tmp/vv-welkom.png' })
  await p.click('[data-act=sheet-loc]'); await p.fill('.search', 'Lemmer'); await p.waitForTimeout(1500)
  await p.screenshot({ path: '/tmp/vv-zoek.png' })
  await p.click('[data-act=pick] >> nth=0')
  await p.waitForSelector('.hero:not(.loading)', { timeout: 30000 })
  await p.waitForTimeout(1500)
  console.log('plek:', await p.textContent('.pname'), '| water:', await p.textContent('[aria-selected=true]'))
  await p.click('.col >> nth=8'); await p.waitForTimeout(400)
  console.log('na tik op uur:', (await p.textContent('.when')).trim())
  const opts = await p.$$eval('.station select option', o => o.slice(0, 3).map(x => x.textContent))
  console.log('getijstations:', opts)
  await p.selectOption('.station select', { index: 2 }); await p.waitForTimeout(800)
  console.log('gekozen station:', await p.textContent('.station span'))
  await p.reload(); await p.waitForSelector('.hero:not(.loading)'); await p.waitForTimeout(800)
  console.log('na herladen:', await p.textContent('.station span'), '| soort:', await p.textContent('.sp.on span'))
  await p.click('[data-act=sheet-info]'); await p.waitForTimeout(500)
  await p.screenshot({ path: '/tmp/vv-info.png' })
  console.log('fouten:', errs.length ? errs : 'geen')
  await b.close()
})()
